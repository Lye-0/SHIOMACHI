export function hintFor(g: Game): Hint {
  if (g.detail && hints[g.detail]) return hints[g.detail]!;
  let detail: Detail;
  if (!g.shutterOpen) detail = "shutter";
  else if (g.items.pliers === "tray" || g.items.keyJig === "tray")
    detail = "tray";
  else if (!g.keyTurn) detail = "key";
  else if (
    !g.drawerOpen ||
    g.items.crank === "drawer" ||
    g.items.hookTip === "drawer"
  )
    detail = "drawer";
  else if (!g.beltTested) detail = "belt";
  else if (!g.strainerClear) detail = "strainer";
  else if (!freePontoon(g)) detail = g.water === 0 ? "supports" : "pipes";
  else if (!soundPontoon(g)) detail = "patch";
  else if (!g.caseOpen || g.items.boatKit === "case") detail = "rings";
  else if (!boatReady(g)) detail = "boat";
  else if (!raised(g)) detail = "window";
  else if (!g.lampLit) detail = "lantern";
  else if (!g.gateOpen) detail = "gate";
  else detail = "chart";
  return hints[detail]!;
}
